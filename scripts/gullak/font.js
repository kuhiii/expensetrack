// bold thickens every stroke sideways by half a font pixel
const boldW = (scale, bold) => (bold ? Math.ceil(scale / 2) : 0);

// proportional metrics: trim empty columns of each glyph
function metrics(ch, prop) {
  const g = G[ch] || G[' '];
  if (!prop) return { g, left: 0, w: 5 };
  if (ch === ' ') return { g, left: 0, w: 3 };
  let l = 5, r = -1;
  for (const row of g) for (let i = 0; i < 5; i++) if (row[i] === '#') { l = Math.min(l, i); r = Math.max(r, i); }
  return r < 0 ? { g, left: 0, w: 3 } : { g, left: l, w: r - l + 1 };
}

function textWidth(str, scale = 1, bold = false, prop = false) {
  const bw = boldW(scale, bold);
  let w = 0;
  for (const ch of str) w += (metrics(ch, prop).w + 1) * scale + bw;
  return w - scale;
}

function text(cv, str, x, y, color, scale = 1, bold = false, prop = false) {
  const bw = boldW(scale, bold);
  let cx = x;
  for (const ch of str) {
    const { g, left, w } = metrics(ch, prop);
    for (let j = 0; j < g.length; j++)
      for (let i = 0; i < 5; i++)
        if (g[j][i] === '#') cv.rect(cx + (i - left) * scale, y + j * scale, scale + bw, scale, color);
    cx += (w + 1) * scale + bw;
  }
  return cx - x;
}

module.exports = { text, textWidth, G };
